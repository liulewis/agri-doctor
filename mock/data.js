// 识别模拟：identify 云函数
// payload: { crop, hint }
function identifySimulate(payload) {
  const p = payload || {}
  // 依据作物 / 提示词稳定地选出一条图谱，保证同样输入结果一致
  let pool = diseases
  if (p.crop && p.crop !== '不确定') {
    const byCrop = diseases.filter(d => d.crop === p.crop)
    if (byCrop.length) pool = byCrop
  }
  const hit = util.pickBy(pool, (p.crop || '') + '|' + (p.hint || '') + '|' + (p.seed || '')) || diseases[0]
  const others = diseases.filter(d => d.id !== hit.id && d.type === hit.type).slice(0, 3)
  const similar = others.map((d, i) => ({
    id: d.id,
    name: d.name,
    crop: d.crop,
    emoji: d.emoji,
    conf: Math.max(0.12, Number((hit.conf - 0.22 - i * 0.11).toFixed(2))),
    percent: util.confPercent(Math.max(0.12, hit.conf - 0.22 - i * 0.11))
  }))
  return {
    success: true,
    result: {
      id: hit.id,
      name: hit.name,
      alias: hit.alias,
      crop: hit.crop,
      type: hit.type,
      typeKey: util.typeKey(hit.type),
      emoji: hit.emoji,
      harm: hit.harm,
      harmKey: util.harmKey(hit.harm),
      season: hit.season,
      pathogen: hit.pathogen,
      summary: hit.summary,
      conf: hit.conf,
      percent: util.confPercent(hit.conf),
      confText: util.fmtConfidence(hit.conf),
      level: util.confLevel(hit.conf),
      levelKey: util.confLevelKey(hit.conf),
      symptoms: hit.symptoms.slice(),
      treatments: hit.treatments.slice(),
      similar: similar
    },
    disclaimer: 'AI 识别结果仅供参考，最终诊断请以农技专家或官方植保部门意见为准。'
  }
}

