// 新建问诊：consultOps action=create
function createConsult(payload) {
  const p = payload || {}
  const expert = experts.find(e => e.id === p.expertId) || experts[0]
  const id = util.uid('c')
  const now = util.formatDateTime(new Date())
  const record = {
    id: id,
    status: 'ongoing',
    statusText: '等待专家接诊',
    crop: p.crop || '通用',
    stage: p.stage || '苗期',
    urgency: p.urgency || URGENCY[0],
    symptom: p.symptom || '',
    expertId: expert.id,
    expertName: expert.name,
    expertAvatar: expert.avatar,
    area: p.area || '未填写',
    location: p.location || '未填写',
    createdAt: now,
    updatedAt: now,
    unread: 0,
    rated: false,
    advice: null,
    messages: [
      { role: 'user', type: 'text', text: p.symptom || '', time: now }
    ]
  }
  const imgs = Number(p.imageCount) || 0
  for (let i = 0; i < imgs; i++) {
    record.messages.push({ role: 'user', type: 'image', text: '田间照片 ' + (i + 1), emoji: '📷', time: now })
  }
  consults.unshift(record)
  return { success: true, id: id, msg: '问诊已提交，专家将尽快接诊' }
}

// 追问：consultOps action=reply
function replyConsult(id, text) {
  const c = consults.find(x => x.id === id)
  if (!c) return { success: false, msg: '问诊记录不存在' }
  const now = util.formatDateTime(new Date())
  c.messages.push({ role: 'user', type: 'text', text: text, time: now })
  c.updatedAt = now
  c.statusText = '等待专家回复'
  return { success: true, msg: '已发送' }
}

// 评价：consultOps action=rate
function rateConsult(id, score, text) {
  const c = consults.find(x => x.id === id)
  if (!c) return { success: false, msg: '问诊记录不存在' }
  c.rated = true
  c.rating = score
  c.ratingText = text || ''
  return { success: true, msg: '感谢你的评价' }
}

