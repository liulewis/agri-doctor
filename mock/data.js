// 图谱详情
function diseaseDetail(id, empty) {
  if (isEmpty(empty)) return { success: true, detail: null }
  const d = diseases.find(x => x.id === id)
  if (!d) return { success: false, msg: '未找到该病害记录' }
  const similar = (d.similar || []).map(sid => {
    const s = diseases.find(x => x.id === sid)
    return s ? { id: s.id, name: s.name, crop: s.crop, emoji: s.emoji } : null
  }).filter(Boolean)
  return {
    success: true,
    detail: Object.assign({}, d, {
      similarList: similar,
      typeKey: util.typeKey(d.type),
      harmKey: util.harmKey(d.harm),
      percent: util.confPercent(d.conf)
    })
  }
}

